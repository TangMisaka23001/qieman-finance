/** 单篇文章对某主题的打分：标签/领域权重 3，标题/摘要/要点权重 1 */
export function themeScore(r, th) {
  const hay = [
    [r.tags || [], 3],
    [r.domain ? [r.domain] : [], 3],
    [[r.title || ''], 1],
    [[r.tldr || ''], 1],
    [(r.core_points || []).join(' '), 1],
  ];
  let n = 0;
  for (const kw of th.kw) {
    for (const [arr, w] of hay) {
      for (const s of arr) {
        if (!s) continue;
        if (s === kw) { n += w * 2; continue; }
        if (String(s).includes(kw)) n += w;
      }
    }
  }
  return n;
}

/** 返回 { theme, themeIndex }；未命中任何关键词时 theme = '其他杂谈' */
export function assignTheme(r) {
  let best = -1, bestN = 0;
  for (let i = 0; i < THEMES.length; i++) {
    const n = themeScore(r, THEMES[i]);
    if (n > bestN) { bestN = n; best = i; }
  }
  return best < 0
    ? { theme: '其他杂谈', themeIndex: -1 }
    : { theme: THEMES[best].name, themeIndex: best };
}
